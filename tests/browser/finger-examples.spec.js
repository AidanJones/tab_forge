import { test, expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';
import { importer, Settings } from '@coderline/alphatab';

test('inline cartoon skeleton diagrams use the hand rig and survive printing without changing saved chords',async({page})=>{
  const errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto('/index.html');
  await page.locator('#input').fill('title: Hands for picking\n[Verse - C]\nnote: Let it ring\n3f5s 2f4s 0s3 1f2s\n[Chorus - F]\n1f6s 3f5s 3f4s 2f3s');
  await page.getByRole('button',{name:'Update preview',exact:true}).click();
  await expect(page.locator('#play')).toBeEnabled();
  await expect(page.locator('#score-finger-examples')).toBeDisabled();
  await page.locator('#score-shapes').check();
  await page.locator('#score-finger-examples').check();
  await page.locator('#score-viewport').scrollIntoViewIfNeeded();
  await expect(page.locator('#score .finger-example-diagram').first()).toBeVisible();
  await expect(page.locator('#score .finger-example-skeleton')).toHaveCount(2);
  await expect(page.locator('#score .cartoon-bone path[stroke]').first()).toBeVisible();
  await expect(page.locator('#score')).toContainText('One possible fingering');
  await expect(page.locator('#score')).toContainText('Let it ring');
  await expect(page.locator('#score')).not.toContainText('__TAB_FORGE');
  await page.locator('#score-viewport').screenshot({path:'test-results/finger-example-score.png'});
  const download=page.waitForEvent('download');
  await page.locator('#save-gp').click();
  const file=await download;
  const score=importer.ScoreLoader.loadScoreFromBytes(await readFile(await file.path()),new Settings());
  expect(score.tracks[0].staves[0].bars[0].voices[0].beats[0].chord.name).toBe('C');
  expect([...score.tracks[0].staves[0].chords.values()].every(chord=>!chord.name.includes('__TAB_FORGE'))).toBe(true);
  await page.evaluate(()=>{const original=window.open;window.open=function(...args){const preview=original.apply(window,args);preview.print=()=>{preview.document.documentElement.dataset.printed='true';};return preview;};});
  const opened=page.waitForEvent('popup');
  await page.locator('#print-score').click();
  const preview=await opened;
  await expect(preview.locator('.finger-example-skeleton')).toHaveCount(2);
  await expect(preview.locator('html')).toHaveAttribute('data-printed','true');
  await preview.screenshot({path:'test-results/finger-example-print.png',fullPage:true});
  await preview.close();
  await page.locator('#speed').fill('25');
  await page.locator('#play').click();
  const before=await page.locator('#position').evaluate(n=>Number(n.value));
  await page.locator('#score-finger-examples').uncheck();
  await expect(page.locator('#play')).toHaveText('Pause');
  await expect(page.locator('#score .finger-example-diagram')).toHaveCount(0);
  await expect.poll(()=>page.locator('#position').evaluate(n=>Number(n.value))).toBeGreaterThan(before);
  await page.locator('#score-finger-examples').check();
  await expect(page.locator('#play')).toHaveText('Pause');
  await page.locator('#score-viewport').scrollIntoViewIfNeeded();
  await expect(page.locator('#score .finger-example-skeleton')).toHaveCount(2);
  await page.locator('#stop').click();
  await page.goto('/practice.html');
  await expect(page.locator('#score-shapes')).toBeChecked();
  await expect(page.locator('#score-finger-examples')).toBeChecked();
  expect(errors).toEqual([]);
});

test('written alternative fingerings produce different examples for the same chord on mobile',async({page})=>{
  const settings=new Settings();
  const score=importer.ScoreLoader.loadAlphaTex('\\tuning E4 B3 G3 D3 A2 E2 \\chord ("C" 0 1 0 2 3 x) . :1 (0.1 1.2 0.3 2.4 3.5){ch "C"} | (0.1 1.2 0.3 2.4 3.5){ch "C"} |',settings);
  const staff=score.tracks[0].staves[0];
  staff.bars.forEach((bar,i)=>bar.voices[0].beats[0].notes.forEach(note=>{
    if(note.fret>0)note.leftHandFinger=({1:1,2:2,3:3})[note.fret]+i;
  }));
  const { exporter }=await import('@coderline/alphatab');
  await page.setViewportSize({width:390,height:844});
  await page.goto('/practice.html');
  await page.locator('#score-shapes').check();
  await page.locator('#score-finger-examples').check();
  await page.locator('#file').setInputFiles({name:'variants.gp',mimeType:'application/octet-stream',buffer:Buffer.from(new exporter.Gp7Exporter().export(score,settings))});
  await expect(page.locator('#play')).toBeEnabled();
  await page.locator('#score-viewport').scrollIntoViewIfNeeded();
  const diagrams=page.locator('#score .finger-example-diagram');
  await expect(diagrams).toHaveCount(2);
  await expect(page.locator('#score .finger-example-skeleton')).toHaveCount(2);
  expect(await diagrams.nth(0).locator('text').allTextContents()).toContain('1');
  expect(await diagrams.nth(1).locator('text').allTextContents()).not.toContain('1');
  expect(await diagrams.nth(1).locator('text').allTextContents()).toContain('4');
  await expect(diagrams.nth(0)).toContainText('Written fingering');
  await expect(diagrams.nth(1)).toContainText('Written fingering');
  expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
  await page.locator('#score-viewport').screenshot({path:'test-results/finger-example-mobile.png'});
});

test('G/B has coloured pressing fingers, faded resting fingers and a tight right crop',async({page})=>{
  await page.goto('/index.html');
  await page.locator('#input').fill('title: G/B fingers\n[Verse - G/B]\n2f5s 0s4 3f2s 3f1s');
  await page.getByRole('button',{name:'Update preview',exact:true}).click();
  await expect(page.locator('#play')).toBeEnabled();
  await page.locator('#score-shapes').check();
  await page.locator('#score-finger-examples').check();
  await page.locator('#score-viewport').scrollIntoViewIfNeeded();
  const diagram=page.locator('#score .finger-example-diagram');
  await expect(diagram).toHaveCount(1);
  await expect(diagram.locator('.finger-example-skeleton')).toHaveCount(1);
  await expect(diagram).not.toContainText('Check fingering');
  await expect(diagram.locator('.finger-2')).toHaveClass(/finger-hovering/);
  await expect(diagram.locator('.finger-1')).toHaveClass(/finger-pressing/);
  const fills=await diagram.locator('.finger-example-finger').evaluateAll(groups=>groups.map(group=>{
    const path=group.querySelector('.cartoon-bone path');
    return path?getComputedStyle(path).fill:null;
  }));
  expect(fills.every(Boolean)).toBe(true);
  expect(new Set(fills).size).toBe(4);
  const alpha=await diagram.locator('.finger-2 .cartoon-bone path').first().evaluate(path=>{
    const channels=getComputedStyle(path).fill.match(/[\d.]+/g).map(Number);
    return channels.length===4?channels[3]:1;
  });
  expect(alpha).toBeLessThan(0.3);
  const bounds=await diagram.locator('.finger-example-skeleton').boundingBox();
  const lastContact=await diagram.locator('text').filter({hasText:/^4$/}).boundingBox();
  expect(bounds.x+bounds.width-lastContact.x).toBeLessThan(18);
  await page.locator('#score-viewport').screenshot({path:'test-results/coloured-gb-fingers.png'});
});
